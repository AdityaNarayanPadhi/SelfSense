"""
ShelfSense Data Contracts & Pydantic Validation Schemas.
"""

from typing import List, Optional
from pydantic import BaseModel, Field


class CompetitorItem(BaseModel):
    """Real-time competitor product pricing and stock listing."""
    title: str = Field(..., description="Competitor listing headline or title")
    price: float = Field(..., description="Normalized price in USD")
    source: str = Field(..., description="Store or merchant name (e.g. Amazon, Walmart, Target)")
    in_stock: bool = Field(..., description="True if item is available for immediate purchase")
    rating: Optional[float] = Field(default=None, description="Average customer star rating (out of 5)")


class TabularForecastResult(BaseModel):
    """TabPFN tabular regression stockout forecast and velocity metrics."""
    predicted_stockout_days: float = Field(
        ...,
        description="Predicted remaining days until inventory reaches zero"
    )
    current_inventory: int = Field(
        ...,
        description="Current units remaining in stock"
    )
    sales_velocity_7d: int = Field(
        ...,
        description="Total units sold in the preceding 7 calendar days"
    )
    risk_level: str = Field(
        ...,
        description="Stockout risk category: 'Immediate' (<3d), 'High' (3-7d), 'Moderate' (7-14d), 'Low' (>14d)"
    )


class ArbitrageStrategy(BaseModel):
    """Dynamic pricing, ad marketing, and spoken brief generated by Gemma reasoning."""
    suggested_price_delta_percent: float = Field(
        ...,
        description="Recommended price adjustment percentage (e.g., +15.0 for 15% price surge, -5.0 for discount)"
    )
    new_suggested_price: float = Field(
        ...,
        description="Recommended selling price based on competitor delta and stockout pressure"
    )
    ad_headlines: List[str] = Field(
        ...,
        description="Three punchy Google/Meta ad headlines under 30 characters each"
    )
    action_steps: List[str] = Field(
        ...,
        description="Actionable tactical execution steps for the merchant"
    )
    spoken_script: str = Field(
        ...,
        description="Natural 60-word morning audio brief transcript (free of markdown and asterisks)"
    )


class AnalysisResponse(BaseModel):
    """Unified response payload returned by the ShelfSense intelligence pipeline."""
    product_query: str = Field(..., description="Product query or ASIN evaluated")
    forecast: TabularForecastResult = Field(..., description="TabPFN stockout forecast")
    competitors: List[CompetitorItem] = Field(..., description="Live competitor price and stock listings")
    strategy: ArbitrageStrategy = Field(..., description="AI-synthesized arbitrage strategy")
    audio_url: str = Field(..., description="URL endpoint to stream the 60s morning spoken brief")


class HealthResponse(BaseModel):
    """Health check response."""
    status: str = "ok"
    service: str = "shelfsense-api"
